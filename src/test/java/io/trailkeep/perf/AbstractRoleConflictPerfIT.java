package io.trailkeep.perf;

import static org.assertj.core.api.Assertions.assertThat;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

import io.trailkeep.testsupport.RequiresDocker;
import io.trailkeep.testsupport.WithAppUser;
import io.trailkeep.user.GlobalRole;
import io.trailkeep.user.UserDirectoryService;
import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.sql.Timestamp;
import java.time.Instant;
import java.time.temporal.ChronoUnit;
import java.util.ArrayList;
import java.util.Collections;
import java.util.List;
import java.util.concurrent.atomic.AtomicBoolean;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Tag;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.boot.webmvc.test.autoconfigure.AutoConfigureMockMvc;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.test.web.servlet.MockMvc;

/**
 * The System screen's role-conflict query at multi-year audit volume (issue 141), once per vendor. The audit trail is
 * seeded with what a deployment of 1 000 people signing in twice a day for seven years holds: 5.11 million
 * {@code USER}/{@code LOGIN} rows, 1 million case events as bulk, and {@code ROLE_CONFLICT} events for 40 people over
 * their last 30 days (10 of whom signed in cleanly afterwards, so 30 conflicts still stand). Then {@code GET
 * /admin/system} and the directory's {@code roleConflicts()} are timed and the query's plan is printed. The seed is
 * synthetic and generated by SQL; nothing here is applied by Flyway or packaged.
 */
// "IT" is the Failsafe suffix Part B mandates for integration tests, not an abbreviation.
@SuppressWarnings("checkstyle:AbbreviationAsWordInName")
@Tag("perf")
@RequiresDocker
@SpringBootTest
@AutoConfigureMockMvc
abstract class AbstractRoleConflictPerfIT {

    static final long ADMIN = 950_000_000L;
    private static final long FIRST_USER = 950_000_001L;
    private static final int USERS = 1_000;
    private static final int CONFLICTED = 40;
    private static final int RESOLVED = 10;
    private static final Instant START = Instant.parse("2019-11-16T00:00:00Z");
    private static final int WARM_UP = 3;
    private static final int SAMPLES = 20;
    private static final AtomicBoolean SEEDED = new AtomicBoolean();
    private static final List<String> REPORT = Collections.synchronizedList(new ArrayList<>());

    /** The standing query as the JPQL of {@code StandingEventQueries} becomes in SQL, with the literals inlined. */
    private static final String STANDING_SQL = "SELECT e.ENTITY_ID, e.AT_TS FROM AUDIT_EVENT e"
            + " WHERE e.CASE_ID IS NULL AND e.ENTITY_TYPE = 'USER' AND e.ACTION = 'ROLE_CONFLICT'"
            + " AND e.ENTITY_ID IS NOT NULL AND NOT EXISTS (SELECT l.ID FROM AUDIT_EVENT l WHERE l.CASE_ID IS NULL"
            + " AND l.ENTITY_TYPE = 'USER' AND l.ENTITY_ID = e.ENTITY_ID AND l.ACTION IN ('LOGIN', 'ROLE_CONFLICT')"
            + " AND (l.AT_TS > e.AT_TS OR (l.AT_TS = e.AT_TS AND l.ID > e.ID))) ORDER BY e.AT_TS, e.ID";

    @Autowired
    private MockMvc mvc;

    @Autowired
    JdbcTemplate jdbc;

    @Autowired
    private UserDirectoryService directory;

    /**
     * The statement that inserts one person's 5 110 sign-ins; parameters: first id, seconds offset of the person,
     * actor id, entity id.
     *
     * @return the SQL
     */
    abstract String loginsSql();

    /**
     * The statement that inserts one million case events; parameters: none.
     *
     * @return the SQL
     */
    abstract String caseEventsSql();

    /**
     * Refreshes the optimizer statistics of the audit table.
     */
    abstract void gatherStatistics();

    /**
     * The vendor's execution plan of {@link #STANDING_SQL}, actually executed, as lines of text.
     *
     * @param sql the statement
     * @return the plan lines
     */
    abstract List<String> plan(String sql);

    abstract String vendor();

    @BeforeEach
    void seedOnce() {
        if (!SEEDED.compareAndSet(false, true)) {
            return;
        }
        long started = System.nanoTime();
        jdbc.update(
                "INSERT INTO APP_USER (ID, EXTERNAL_ID, DISPLAY_NAME, EMAIL, DISABLED, CREATED_AT)"
                        + " VALUES (?, 'perf-sysadmin', 'Perf System Admin', 'perf@example.invalid', ?, ?)",
                ADMIN,
                false,
                Timestamp.from(START));
        jdbc.update(
                "INSERT INTO APP_USER_GLOBAL_ROLE (USER_ID, GLOBAL_ROLE) VALUES (?, ?)",
                ADMIN,
                GlobalRole.SYSTEM_ADMIN.name());
        for (int u = 0; u < USERS; u++) {
            long id = FIRST_USER + u;
            jdbc.update(
                    "INSERT INTO APP_USER (ID, EXTERNAL_ID, DISPLAY_NAME, EMAIL, DISABLED, CREATED_AT)"
                            + " VALUES (?, ?, ?, 'user@example.invalid', ?, ?)",
                    id,
                    "perf-user-" + u,
                    "Perf User " + u,
                    false,
                    Timestamp.from(START));
            jdbc.update(loginsSql(), 700_000_000_000L + u * 10_000L, u, id, id);
        }
        jdbc.update(caseEventsSql());
        List<Object[]> conflicts = new ArrayList<>();
        long conflictId = 800_000_000_000L;
        for (int u = 0; u < CONFLICTED; u++) {
            int lastDay = u < RESOLVED ? 2_549 : 2_554; // resolved people signed in cleanly on the days after
            for (int day = 2_525; day <= lastDay; day++) {
                for (int s = 0; s < 2; s++) {
                    Instant at = START.plus(day, ChronoUnit.DAYS)
                            .plus(s * 8L, ChronoUnit.HOURS)
                            .plusSeconds(u + 1L);
                    conflicts.add(new Object[] {conflictId++, Timestamp.from(at), FIRST_USER + u, FIRST_USER + u});
                }
            }
        }
        jdbc.batchUpdate(
                "INSERT INTO AUDIT_EVENT (ID, AT_TS, ACTOR_ID, ORIGIN, ENTITY_TYPE, ENTITY_ID, ACTION)"
                        + " VALUES (?, ?, ?, 'UI', 'USER', ?, 'ROLE_CONFLICT')",
                conflicts);
        gatherStatistics();
        REPORT.add("Seed on " + vendor() + ": "
                + jdbc.queryForObject("SELECT COUNT(*) FROM AUDIT_EVENT", Long.class) + " audit events ("
                + jdbc.queryForObject("SELECT COUNT(*) FROM AUDIT_EVENT WHERE ACTION = 'ROLE_CONFLICT'", Long.class)
                + " ROLE_CONFLICT), applied in " + (System.nanoTime() - started) / 1_000_000 + " ms");
    }

    @Test
    @WithAppUser(id = ADMIN, globalRole = GlobalRole.SYSTEM_ADMIN)
    void theSystemScreenAndItsQueryAtSevenYearsOfSignIns() throws Exception {
        assertThat(directory.roleConflicts()).as("standing conflicts").hasSize(CONFLICTED - RESOLVED);
        REPORT.add(timed("roleConflicts() alone", () -> directory.roleConflicts()));
        REPORT.add(timed("GET /admin/system", () -> {
            try {
                mvc.perform(get("/admin/system")).andExpect(status().isOk());
            } catch (Exception e) {
                throw new IllegalStateException(e);
            }
        }));
        REPORT.add("Plan of the standing query:\n" + String.join("\n", plan(STANDING_SQL)));
        String candidate = System.getProperty("perf.index.ddl", "");
        if (!candidate.isBlank()) {
            for (String ddl : candidate.split(";;", -1)) {
                jdbc.execute(ddl);
            }
            gatherStatistics();
            REPORT.add("After: " + candidate);
            REPORT.add(timed("roleConflicts() alone", () -> directory.roleConflicts()));
            REPORT.add(timed("GET /admin/system", () -> {
                try {
                    mvc.perform(get("/admin/system")).andExpect(status().isOk());
                } catch (Exception e) {
                    throw new IllegalStateException(e);
                }
            }));
            REPORT.add("Plan of the standing query:\n" + String.join("\n", plan(STANDING_SQL)));
        }
        Path out = Path.of("target", "perf", "role-conflict-" + vendor() + ".md");
        try {
            Files.createDirectories(out.getParent());
            Files.writeString(out, String.join("\n\n", REPORT) + "\n");
        } catch (IOException e) {
            throw new IllegalStateException(e);
        }
        System.out.println("=== ROLE-CONFLICT PERF " + vendor() + " ===\n" + String.join("\n\n", REPORT));
    }

    private static String timed(String name, Runnable call) {
        for (int i = 0; i < WARM_UP; i++) {
            call.run();
        }
        long[] ms = new long[SAMPLES];
        for (int i = 0; i < SAMPLES; i++) {
            long t = System.nanoTime();
            call.run();
            ms[i] = (System.nanoTime() - t) / 1_000_000;
        }
        java.util.Arrays.sort(ms);
        return name + ": p50 " + ms[SAMPLES / 2] + " ms, p95 " + ms[(int) Math.ceil(SAMPLES * 0.95) - 1] + " ms, max "
                + ms[SAMPLES - 1] + " ms (" + SAMPLES + " samples)";
    }
}
